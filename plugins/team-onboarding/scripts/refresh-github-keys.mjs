// Refreshes the GitHub SSH host keys the plugin pins, from api.github.com/meta.
// Run before a release: `npm run refresh-keys`. The output is committed, so
// installs never trust a key fetched on first contact.
import { writeFileSync } from "node:fs";

const response = await fetch("https://api.github.com/meta", {
  headers: { accept: "application/vnd.github+json" },
});
if (!response.ok) throw new Error(`api.github.com/meta answered ${response.status}`);
const meta = await response.json();
const keys = meta.ssh_keys;
if (!Array.isArray(keys) || keys.length === 0) throw new Error("no ssh_keys in meta");
const lines = keys.map((key) => `github.com ${key}`);
const out = `// Generated by scripts/refresh-github-keys.mjs from api.github.com/meta on
// ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
export const GITHUB_KNOWN_HOSTS: readonly string[] = ${JSON.stringify(lines, null, 2)};

export const GITHUB_KEY_FINGERPRINTS: Readonly<Record<string, string>> = ${JSON.stringify(meta.ssh_key_fingerprints ?? {}, null, 2)};
`;
writeFileSync(new URL("../src/core/github-keys.ts", import.meta.url), out);
console.log(`pinned ${lines.length} keys`);
