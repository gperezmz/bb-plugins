// Writes THIRD_PARTY_NOTICES.md: every third-party package bundled into
// dist/. Server and host packages come from their source maps; the app
// bundle has none, so its inputs come from an esbuild metafile built with the
// same externals bb shims at runtime. Run after `bb plugin build .`:
//
//   node scripts/third-party-notices.mjs
//
// esbuild is found in node_modules, in bb's plugin toolchain
// (~/.bb/plugins/toolchain-*), or at $ESBUILD.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;

/** Packages bb provides to plugin frontends at runtime; never bundled. */
const APP_EXTERNALS = [
  "react", "react/*", "react-dom", "react-dom/*", "@get-bb/plugin-sdk", "@get-bb/plugin-sdk/*",
  "sonner", "vaul", "clsx", "tailwind-merge", "class-variance-authority", "@pierre/diffs",
  "@radix-ui/react-alert-dialog", "@radix-ui/react-context-menu", "@radix-ui/react-dialog",
  "@radix-ui/react-dropdown-menu", "@radix-ui/react-hover-card", "@radix-ui/react-menubar",
  "@radix-ui/react-navigation-menu", "@radix-ui/react-popover", "@radix-ui/react-select",
  "@radix-ui/react-tooltip",
];

function packageOf(path) {
  const rest = path.split("node_modules/").pop().split("/");
  return rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
}

function fromSourceMap(file) {
  const map = JSON.parse(readFileSync(join(root, file), "utf8"));
  return map.sources.filter((source) => source.includes("node_modules/")).map(packageOf);
}

function findEsbuild() {
  if (process.env.ESBUILD) return process.env.ESBUILD;
  const local = join(root, "node_modules/esbuild/bin/esbuild");
  if (existsSync(local)) return local;
  const plugins = join(homedir(), ".bb/plugins");
  for (const dir of existsSync(plugins) ? readdirSync(plugins).filter((name) => name.startsWith("toolchain-")).sort().reverse() : []) {
    const candidate = join(plugins, dir, "node_modules/esbuild/bin/esbuild");
    if (existsSync(candidate)) return candidate;
  }
  throw new Error("esbuild not found; set ESBUILD");
}

function fromAppBundle() {
  const out = mkdtempSync(join(tmpdir(), "notices-"));
  try {
    execFileSync(findEsbuild(), [
      "app.tsx", "--bundle", "--format=esm", "--minify", "--log-level=error",
      `--metafile=${join(out, "meta.json")}`, `--outfile=${join(out, "app.js")}`,
      "--loader:.css=empty", `--alias:@=${root}`,
      ...APP_EXTERNALS.map((name) => `--external:${name}`),
    ], { cwd: root });
    const meta = JSON.parse(readFileSync(join(out, "meta.json"), "utf8"));
    const output = Object.values(meta.outputs)[0];
    return Object.keys(output.inputs).filter((input) => input.includes("node_modules/") && output.inputs[input].bytesInOutput > 0).map(packageOf);
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

function copyrightOf(dir) {
  for (const name of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "LICENCE", "COPYING"]) {
    const file = join(dir, name);
    if (!existsSync(file)) continue;
    const line = readFileSync(file, "utf8").split("\n").map((text) => text.trim()).find((text) => /^copyright\b|^\(c\)|©/i.test(text));
    if (line) return line;
  }
  return null;
}

const bundles = {
  "dist/server.js": fromSourceMap("dist/server.js.map"),
  "dist/host.js": fromSourceMap("dist/host.js.map"),
  "dist/app.js": fromAppBundle(),
};
const packages = new Map();
for (const [bundle, names] of Object.entries(bundles)) {
  for (const name of names) {
    if (!packages.has(name)) packages.set(name, new Set());
    packages.get(name).add(bundle);
  }
}

const rows = [...packages.keys()].sort().map((name) => {
  const dir = join(root, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licence = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "not declared in its package.json");
  const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
  const copyright = copyrightOf(dir) ?? (author ? `Copyright (c) ${author}` : "no copyright line in the package");
  return { name, version: pkg.version, licence, copyright, bundles: [...packages.get(name)].sort().join(", ") };
});

const lines = [
  "# Third-party notices",
  "",
  "Team Onboarding's built files (`dist/`) include code from these packages. Each keeps its own licence; the full licence texts ship with the packages on npm. Generated by `scripts/third-party-notices.mjs` from the bundles' inputs.",
  "",
  "| Package | Version | Licence | Copyright | In |",
  "|---|---|---|---|---|",
  ...rows.map((row) => `| ${row.name} | ${row.version} | ${row.licence} | ${row.copyright.replace(/\|/g, "\\|")} | ${row.bundles} |`),
  "",
  "The files in `components/ui/`, `hooks/`, `lib/utils.ts` and `lib/portal-scope.ts` are vendored from the component registry `bb plugin new` scaffolds from, which follows the shadcn/ui pattern (MIT, Copyright (c) 2023 shadcn).",
  "",
];
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), lines.join("\n"));
console.log(`${rows.length} packages`);
