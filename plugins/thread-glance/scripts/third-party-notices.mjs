// Writes THIRD_PARTY_NOTICES.md: every third-party package the plugin's
// bundles contain. It re-bundles app.tsx and server.ts with esbuild's
// metafile, leaving out what bb provides at runtime (the same shims
// `bb plugin build` leaves out), and reads each package's own manifest and
// licence file. Run with `npm run notices` after changing dependencies.
import { build } from "esbuild";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Provided by bb at runtime, never bundled (bb's plugin authoring docs).
const APP_RUNTIME = [
  "react",
  "react/*",
  "react-dom",
  "react-dom/*",
  "@get-bb/plugin-sdk",
  "@get-bb/plugin-sdk/*",
  "@radix-ui/react-dialog",
  "@radix-ui/react-alert-dialog",
  "@radix-ui/react-popover",
  "@radix-ui/react-select",
  "@radix-ui/react-dropdown-menu",
  "@radix-ui/react-context-menu",
  "@radix-ui/react-menubar",
  "@radix-ui/react-hover-card",
  "@radix-ui/react-tooltip",
  "@radix-ui/react-navigation-menu",
  "sonner",
  "vaul",
  "@pierre/diffs",
  "@pierre/diffs/*",
  "clsx",
  "tailwind-merge",
  "class-variance-authority",
];
const SERVER_RUNTIME = ["@get-bb/plugin-sdk", "@get-bb/plugin-sdk/*", "better-sqlite3"];

async function inputs(entry, external, platform) {
  const result = await build({
    entryPoints: [join(root, entry)],
    bundle: true,
    write: false,
    metafile: true,
    platform,
    format: "esm",
    jsx: "automatic",
    external,
    alias: { "@": root },
    loader: { ".svg": "text", ".png": "empty", ".css": "empty" },
    logLevel: "silent",
  });
  return Object.keys(result.metafile.inputs);
}

function packageDirOf(input) {
  const marker = "node_modules/";
  const at = input.lastIndexOf(marker);
  if (at < 0) return null;
  const rest = input.slice(at + marker.length).split("/");
  const name = rest[0].startsWith("@") ? `${rest[0]}/${rest[1]}` : rest[0];
  return { name, dir: join(root, input.slice(0, at + marker.length), name) };
}

function copyrightOf(dir) {
  const file = readdirSync(dir).find((entry) => /^(licen[cs]e|copying)(\.|$)/i.test(entry));
  if (file === undefined) return { line: null, text: null };
  const text = readFileSync(join(dir, file), "utf8").trim();
  const line = text.split("\n").find((candidate) => /copyright\s+(\(c\)|©|\d{4})/i.test(candidate)) ?? null;
  return { line: line?.trim() ?? null, text };
}

const found = new Map();
for (const [entry, external, platform, bundle] of [
  ["app.tsx", APP_RUNTIME, "browser", "app"],
  ["server.ts", SERVER_RUNTIME, "node", "server"],
]) {
  for (const input of await inputs(entry, external, platform)) {
    const pkg = packageDirOf(input);
    if (pkg === null || !existsSync(join(pkg.dir, "package.json"))) continue;
    const entryInfo = found.get(pkg.name) ?? { dir: pkg.dir, bundles: new Set() };
    entryInfo.bundles.add(bundle);
    found.set(pkg.name, entryInfo);
  }
}

const rows = [...found.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, { dir, bundles }]) => {
    const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const license = typeof manifest.license === "string" ? manifest.license : manifest.license?.type ?? "UNKNOWN";
    const { line, text } = copyrightOf(dir);
    const author = typeof manifest.author === "string" ? manifest.author : manifest.author?.name;
    return { name, version: manifest.version, license, bundles: [...bundles].sort(), line, author, text };
  });

const out = [
  "# Third-party notices",
  "",
  "Thread Glance's built bundles (`dist/app.js`, `dist/server.js`) include the packages below. Packages bb provides at runtime (React, the Radix overlay families, sonner, vaul, clsx, tailwind-merge, class-variance-authority, the bb plugin SDK) are not bundled and are not listed.",
  "",
  "This file is generated by `npm run notices` (`scripts/third-party-notices.mjs`).",
  "",
  "| Package | Version | Licence | Bundle | Copyright |",
  "|---|---|---|---|---|",
  ...rows.map(
    (row) =>
      `| ${row.name} | ${row.version} | ${row.license} | ${row.bundles.join(", ")} | ${(row.line ?? (row.author ? `Copyright ${row.author}` : "See the licence text")).replace(/\|/g, "\\|")} |`,
  ),
  "",
  "## Vendored source",
  "",
  "`components/ui/`, `lib/utils.ts`, `lib/portal-scope.ts` and `hooks/useBrowserDimmingModal.ts` were copied, as `bb plugin new` and `npx shadcn add` do, from bb's component registry (`packages/plugin-registry` in the `get-bb/bb` repository, pinned to the `desktop-v0.43.4` tag in `components.json`). The registry generates them from bb's own components, which follow shadcn/ui (MIT, Copyright (c) 2023 shadcn). The installed bb 0.43.4 packages state no licence of their own for this source.",
  "",
  "## Licence texts",
  "",
];
for (const row of rows) {
  if (row.text === null) {
    out.push(`### ${row.name} ${row.version}`, "", `Licensed under ${row.license}; the package ships no licence file.`, "");
    continue;
  }
  out.push(`### ${row.name} ${row.version}`, "", "```text", row.text, "```", "");
}
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), `${out.join("\n").trimEnd()}\n`);
console.log(`THIRD_PARTY_NOTICES.md: ${rows.length} packages`);
for (const row of rows) console.log(`${row.name}@${row.version} ${row.license} [${row.bundles.join(",")}] ${row.line ?? ""}`);
